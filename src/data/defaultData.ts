function buildExactCurriculum(
  courseName: CourseName,
  grade: number,
  specs: ExactWeekSpec[],
  idPrefix: string
): CurriculumEntry[] {
  const entries: CurriculumEntry[] = [];

  for (let week = 1; week <= 37; week++) {
    const matched =
      specs.find((s) => s.weeks.includes(week)) || specs[specs.length - 1];
    const weekMeta = WEEK_DATE_RANGES[week] || { range: `${week}. Hafta` };

    entries.push({
      id: `${idPrefix}-w${week}`,
      course_name: courseName,
      grade,
      week,
      date_range: weekMeta.range,
      unit: matched.unit,
      content_framework: matched.content,
      learning_outcome: matched.outcome,
      outcome_code: matched.code,
      explanation: matched.explanation,
      methods_and_techniques: matched.methods,
      values_and_skills: matched.values,
      special_days: weekMeta.specialDays,
    });
  }

  return entries;
}

