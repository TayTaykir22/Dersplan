function convertRowsToCurriculum(
  courseName: CourseName,
  grade: number,
  rows: PdfWeekRow[],
  prefix: string
): CurriculumEntry[] {
  return rows.map((r) => ({
    id: `${prefix}-w${r.week}`,
    course_name: courseName,
    grade,
    week: r.week,
    date_range: r.date_range,
    unit: r.unit,
    content_framework: r.content_framework,
    learning_outcome: r.learning_outcome,
    outcome_code: r.outcome_code,
    methods_and_techniques: r.explanation,
    values_and_skills: 'İstiklal Ortaokulu Yıllık Planı (Zümre: Barış Kır, Hamza Erdoğan)',
    special_days: r.special_days || PDF_WEEK_DATES[r.week]?.specialDays,
  }));
}

